@pytest.mark.anyio
async def test_pipeline_analyzing_success_article(tmp_path: Path) -> None:
    """Verify normal article pipeline transitions to analyzing, synthesizes note, and rebuilds index."""
    db_path = tmp_path / "test_analyzing.db"
    store = Store(str(db_path))
    save_id = await seed_save(store, "https://example.com/future-computing", platform="web")

    extractor = MockExtractor()
    llm = MockControlledLLM()
    engine = PipelineEngine(store, article_extractor=extractor, llm_provider=llm, media_base_dir=tmp_path / "media")

    res = await engine.process_save(save_id)

    # Verify pipeline summary
    assert res["state"] == JobState.READY
    assert res["failed"] == []
    assert JobStage.ANALYZING in res["timings"]
    assert len(llm.calls) == 1
    assert llm.calls[0]["title"] == "The Future of Computing"
    assert "distributed architectures" in llm.calls[0]["content"]

    # Verify note persisted
    note = await store.fetchone("SELECT * FROM notes WHERE save_id=?", (save_id,))
    assert note is not None
    assert "## Overview" in note["markdown"]
    assert "A comprehensive overview generated by LLM." in note["markdown"]
    assert "## Key points" in note["markdown"]
    assert "- Point 1: core insight" in note["markdown"]
    assert "## Links mentioned" in note["markdown"]
    assert "[Timestamp Ref](https://example.com/video) (0:42)" in note["markdown"]
    assert note["overview"] == "A comprehensive overview generated by LLM."

    # Verify sections table populated
    sections = await store.fetchall("SELECT heading, anchor FROM note_sections WHERE save_id=? ORDER BY seq ASC", (save_id,))
    assert len(sections) >= 3
    headings = [s["heading"] for s in sections]
    assert "Overview" in headings
    assert "Key points" in headings
    assert "Links mentioned" in headings

    # Verify FTS5 search
    fts = await store.fetchall("SELECT save_id FROM notes_fts WHERE notes_fts MATCH 'comprehensive'")
    assert len(fts) == 1
    assert fts[0]["save_id"] == save_id


