@pytest.mark.anyio
async def test_pipeline_analyzing_graceful_degradation_on_llm_failure(tmp_path: Path) -> None:
    """Verify missing credentials or LLM error degrades gracefully: sets needs_review and marks analyzing failed."""
    db_path = tmp_path / "test_llm_failure.db"
    store = Store(str(db_path))
    save_id = await seed_save(store, "https://example.com/article", platform="web")

    extractor = MockExtractor()
    failing_llm = MockControlledLLM(
        result=NoteGenerationResult(
            is_success=False,
            error_category="missing_credentials",
        )
    )
    engine = PipelineEngine(store, article_extractor=extractor, llm_provider=failing_llm, media_base_dir=tmp_path / "media")

    res = await engine.process_save(save_id)

    # Job completes to ready with analyzing marked as failed
    assert res["state"] == JobState.READY
    assert JobStage.ANALYZING in res["failed"]
    assert res["error"] == ErrorCode.LLM_UNAVAILABLE

    # Save marked for review
    save = await store.fetchone("SELECT needs_review FROM saves WHERE id=?", (save_id,))
    assert save is not None
    assert save["needs_review"] == 1

    # Note exists with degraded shell
    note = await store.fetchone("SELECT * FROM notes WHERE save_id=?", (save_id,))
    assert note is not None
    assert "## Overview" in note["markdown"]
    assert "_Note overview generation unavailable._" in note["markdown"]
    assert "An extensive article discussing modern distributed architectures" in note["markdown"]


@pytest.mark.anyio
async def test_pipeline_reprocess_preserves_user_body(tmp_path: Path) -> None:
    """Verify reprocessing from extracting/transcribing updates metadata but preserves user-edited body (ADR 0005)."""
    db_path = tmp_path / "test_reprocess_preserve.db"
    store = Store(str(db_path))
    save_id = await seed_save(store, "https://example.com/article", platform="web")

    # Manually seed an existing note with user edits
    user_body = """---
source: web
channel: Original Channel
folder: Tech
tags: ["original"]
---
# Custom User Title

## User Custom Section
This is custom prose written by the user that must NEVER be overwritten on reprocess!

## Overview
Custom user overview.
"""
    await store.run_tx(
        lambda conn: execute_note_persistence_transaction(
            conn=conn,
            save_id=save_id,
            markdown=user_body,
            overview="Custom user overview.",
        )
    )

    # Updated extractor returning new channel name
    extractor = MockExtractor(
        result=ExtractionResult(
            tier=1,
            kind=Kind.ARTICLE,
            title="Updated Title From Web",
            channel="Updated Channel Name",
            body="New scraped body text",
            transcript_available=False,
            capability_flags=CapabilityFlags(),
        )
    )
    llm = MockControlledLLM()
    engine = PipelineEngine(store, article_extractor=extractor, llm_provider=llm, media_base_dir=tmp_path / "media")

    # Reprocess from 'extracting'
    res = await engine.process_save(save_id, from_stage="extracting")
    assert res["state"] == JobState.READY

    # LLM must NOT have been called to regenerate the body!
    assert len(llm.calls) == 0

    # Note body must be strictly preserved!
    note = await store.fetchone("SELECT * FROM notes WHERE save_id=?", (save_id,))
    assert note is not None
    assert "This is custom prose written by the user that must NEVER be overwritten on reprocess!" in note["markdown"]
    assert "channel: Updated Channel Name" in note["markdown"]
    assert note["overview"] == "Custom user overview."


@pytest.mark.anyio
async def test_pipeline_reprocess_explicit_analyzing_regenerates_body(tmp_path: Path) -> None:
    """Verify explicit reprocessing with from=analyzing regenerates note body."""
    db_path = tmp_path / "test_reprocess_explicit.db"
    store = Store(str(db_path))
    save_id = await seed_save(store, "https://example.com/article", platform="web")

    # Seed existing note
    initial_body = """---
source: web
---
# Old Note
## Overview
Old overview.
"""
    await store.run_tx(
        lambda conn: execute_note_persistence_transaction(
            conn=conn,
            save_id=save_id,
            markdown=initial_body,
            overview="Old overview.",
        )
    )

    llm = MockControlledLLM(
        result=NoteGenerationResult(
            is_success=True,
            structured_output=NoteStructuredOutput(
                overview="Brand New Regenerated Overview!",
                key_points=["Regenerated Point 1"],
                links=[],
            ),
        )
    )
    engine = PipelineEngine(store, llm_provider=llm, media_base_dir=tmp_path / "media")

    # Persist extraction result so from=analyzing can load article body
    await engine._persist_extraction_result(
        save_id,
        ExtractionResult(
            tier=1,
            kind=Kind.ARTICLE,
            title="Article",
            channel="Channel",
            body="Article body to regenerate from.",
            transcript_available=False,
            capability_flags=CapabilityFlags(),
        ),
    )

    res = await engine.process_save(save_id, from_stage="analyzing")
    assert res["state"] == JobState.READY
    assert len(llm.calls) == 1

    note = await store.fetchone("SELECT * FROM notes WHERE save_id=?", (save_id,))
    assert note is not None
    assert "Brand New Regenerated Overview!" in note["markdown"]
    assert note["overview"] == "Brand New Regenerated Overview!"
