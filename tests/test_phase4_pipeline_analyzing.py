class MockExtractor:
    def __init__(self, result: ExtractionResult | None = None) -> None:
        self.result = result or ExtractionResult(
            tier=1,
            kind=Kind.ARTICLE,
            title="The Future of Computing",
            channel="Tech Weekly",
            body="An extensive article discussing modern distributed architectures and AI systems.",
            transcript_available=False,
            capability_flags=CapabilityFlags(has_audio=False, has_timeline=False, has_images=False),
        )

    async def extract(self, url: str, platform: str) -> ExtractionResult:
        return self.result


class MockASR:
    async def transcribe(self, audio_path: Path, language: str | None = None) -> str:
        return "Spoken video transcript detailing the key ideas of modern software engineering."


class MockControlledLLM:
    def __init__(
        self,
        result: NoteGenerationResult | None = None,
        raise_err: Exception | None = None,
    ) -> None:
        self.result = result or NoteGenerationResult(
            is_success=True,
            structured_output=NoteStructuredOutput(
                overview="A comprehensive overview generated by LLM.",
                key_points=["Point 1: core insight", "Point 2: architecture", "Point 3: results"],
                links=[
                    LinkItem(anchor_text="Source Article", url="https://example.com/source", jump_target=None),
                    LinkItem(anchor_text="Timestamp Ref", url="https://example.com/video", jump_target="0:42"),
                ],
            ),
        )
        self.raise_err = raise_err
        self.calls: list[dict[str, Any]] = []

    async def generate_note(
        self,
        title: str,
        kind: str,
        content: str,
        user_context: str | None = None,
    ) -> NoteGenerationResult:
        self.calls.append({"title": title, "kind": kind, "content": content, "user_context": user_context})
        if self.raise_err:
            raise self.raise_err
        return self.result


async def seed_save(store: Store, url: str = "https://example.com/article", platform: str = "web") -> str:
    save_id = new_uuid7()
    now = now_iso_z()

    def _tx(conn: Any) -> None:
        conn.execute(
            "INSERT INTO saves(id, raw_url, url, platform, source_app, user_context, captured_at, created_at, updated_at)"
            " VALUES (?, ?, ?, ?, 'test_app', 'context from user', ?, ?, ?)",
            (save_id, url, url, platform, now, now, now),
        )
        conn.execute(
            "INSERT INTO notes(save_id, markdown, created_at, updated_at) VALUES (?, '---\n---\n', ?, ?)",
            (save_id, now, now),
        )
        conn.execute(
            "INSERT INTO jobs(save_id, state, tier, created_at, updated_at) VALUES (?, 'queued', 1, ?, ?)",
            (save_id, now, now),
        )

    await store.run_tx(_tx)
    return save_id


